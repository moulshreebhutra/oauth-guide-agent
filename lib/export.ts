import type { Guide } from "./schema";

const who: Record<string, string> = { you: "YOU", agent: "AGENT", either: "EITHER" };

/** A plain-Markdown copy of a guide, with its sources, for docs, tickets or chat. */
export function guideMarkdown(g: Guide): string {
  const L: string[] = [];
  L.push(`# ${g.app}: OAuth app setup`, "", g.summary, "");
  L.push(`- Difficulty: tier ${g.difficulty.tier} (${g.difficulty.label}). ${g.difficulty.rationale}`);
  L.push(`- Your time: ${g.effort.hands_on_minutes.min}-${g.effort.hands_on_minutes.max} minutes [${g.effort.tag}]. ${g.effort.basis}`);
  L.push(`- Approval wait: ${g.wait.headline ?? g.wait.display ?? "see below"} [${g.wait.tag}]. ${g.wait.statement}`);
  L.push(`- Composio managed auth: ${g.composio_managed.status} [${g.composio_managed.tag}]. ${g.composio_managed.note}`, "");
  L.push("## Steps");
  for (const s of g.steps) L.push(`${s.n}. **${s.title}** (${who[s.who] ?? s.who}) [${s.tag}] ${s.detail}${s.why_not_agent ? ` Why not the agent: ${s.why_not_agent}` : ""}`);
  L.push("", "## Requirements", ...g.requirements.map((c) => `- ${c.text} [${c.tag}]`));
  if (g.gotchas.length) L.push("", "## Gotchas", ...g.gotchas.map((c) => `- ${c.text} [${c.tag}]`));
  if (g.blockers.length) L.push("", "## If you get stuck", ...g.blockers.map((b) => `- ${b.symptom}: ${b.likely_cause} Fix: ${b.fix} Escalate when: ${b.escalate_when}`));
  L.push("", "## What we are unsure about", ...g.uncertainties.map((u) => `- ${u}`));
  L.push("", "## Sources", ...g.evidence.map((e) => `- [${e.id}] ${e.title}: ${e.url} ("${e.excerpt}")`));
  L.push("", `_Last verified ${g.last_verified}. Tags: tested, sourced, reported, inferred, unknown. Generated by OAuth Route Map._`);
  return L.join("\n");
}

/** A task brief to paste into a coding agent: it does the agent steps, and stops where a person must act. */
export function agentBrief(g: Guide): string {
  const agentSteps = g.steps.filter((s) => s.who !== "you");
  const youSteps = g.steps.filter((s) => s.who !== "agent");
  const L: string[] = [];
  L.push(`# Task: prepare the ${g.app} OAuth app setup`, "", `Goal: get an OAuth app for ${g.app} ready for use in our product. Difficulty tier ${g.difficulty.tier} (${g.difficulty.label}); expected wait: ${g.wait.headline ?? g.wait.display ?? "not published"}.`, "");
  L.push("## You (the agent) can do", ...g.agent_vs_you.agent_can.map((x) => `- ${x}`));
  if (agentSteps.length) L.push("", "## Steps assigned to you or shared", ...agentSteps.map((s) => `- ${s.title}: ${s.detail}`));
  L.push("", "## STOP and hand back to the human for", ...g.agent_vs_you.you_must.map((x) => `- ${x}`));
  if (youSteps.length) L.push("", "## Human steps (do not attempt)", ...youSteps.filter((s) => s.who === "you").map((s) => `- ${s.title}${s.why_not_agent ? ` (${s.why_not_agent})` : ""}`));
  L.push("", "## Requirements to check before the human submits", ...g.requirements.map((c) => `- ${c.text}`));
  L.push("", "## Rules", "- Never ask for, print or store secrets (client secrets, tokens, passwords). Tell the human where to put them (host environment variables).", "- Do not sign in, accept terms, verify a domain or business, pay, or submit for review. Stop and say what is needed.", "- If a page contradicts this brief, trust the provider's page and say so.", "", `Reference: https://oauth-guide-agent.vercel.app/guide/${g.slug} (last verified ${g.last_verified}).`);
  return L.join("\n");
}
